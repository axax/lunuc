export const Avatar = ({name, picture, group, size = 40}) => {
    const src = pictureSrc(picture)
    const style = {width: size, height: size, fontSize: Math.round(size * 0.4)}
    if (src) {
        return <img className="lchat-avatar" style={style} src={src} alt="" loading="lazy"/>
    }
    return <span className="lchat-avatar" style={{...style, backgroundColor: colorFor(name)}}>
        {group ? <Icon name="group" size={Math.round(size * 0.58)}/> : initials(name)}
    </span>
}

/* calls onClose on a click outside of the element or on escape */
export const useDismiss = (onClose, active = true) => {
    const ref = useRef(null)
    useEffect(() => {
        if (!active) return
        const onDown = (e) => {
            if (ref.current && !ref.current.contains(e.target)) onClose()
        }
        const onKey = (e) => {
            if (e.key === 'Escape') onClose()
        }
        document.addEventListener('mousedown', onDown)
        document.addEventListener('touchstart', onDown)
        document.addEventListener('keydown', onKey)
        return () => {
            document.removeEventListener('mousedown', onDown)
            document.removeEventListener('touchstart', onDown)
            document.removeEventListener('keydown', onKey)
        }
    }, [active])
    return ref
}

export const Modal = ({title, onClose, children, footer, wide}) => {
    const ref = useDismiss(onClose)
    return <div className="lchat-modal-backdrop">
        <div className={'lchat-modal' + (wide ? ' lchat-modal--wide' : '')} ref={ref} role="dialog" aria-modal="true" aria-label={title}>
            <div className="lchat-modal-head">
                <IconButton icon="close" title="Close" onClick={onClose}/>
                <span>{title}</span>
            </div>
            <div className="lchat-modal-body">{children}</div>
            {footer && <div className="lchat-modal-foot">{footer}</div>}
        </div>
    </div>
}

